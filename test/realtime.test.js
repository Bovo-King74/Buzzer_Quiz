'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const net = require('node:net');
const client = require('../node_modules/socket.io/client-dist/socket.io.js');
const liveGame = require('../lib/live-game');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const game = () => ({ started: true, phase: 'locked', ans: null, answered: new Set(), order: [], done: false, undo: [], live: liveGame.init(), players: { a: { id: 'a', sid: 'a', st: 'ok' }, b: { id: 'b', sid: 'b', st: 'ok' }, c: { id: 'c', sid: 'c', st: 'ok' } } });

test('shared deadline opens only at server expiry; pause preserves remaining countdown', () => {
  const g = game(); assert.ok(liveGame.action(g, { type: 'countdown:start' }, 1000).ok);
  liveGame.advance(g, 1999); assert.equal(g.phase, 'locked');
  liveGame.action(g, { type: 'pause' }, 2000); assert.equal(g.live.countdown.remainingMs, 2000);
  liveGame.advance(g, 9000); assert.equal(g.phase, 'locked');
  liveGame.action(g, { type: 'resume' }, 10000); assert.equal(g.live.countdown.endsAt, 12000);
  liveGame.advance(g, 11999); assert.equal(g.phase, 'locked');
  liveGame.advance(g, 12000); assert.equal(g.phase, 'open'); assert.equal(g.live.countdown, null);
});
test('duel membership, mode compatibility, disconnections and deterministic shared draw', () => {
  const g = game(); assert.equal(liveGame.action(g, { type: 'duel:start', ids: ['a', 'a'] }).ok, false);
  assert.ok(liveGame.action(g, { type: 'duel:start', ids: ['a', 'b'] }).ok);
  assert.equal(liveGame.mode(g, g.players.c), 'spectator');
  assert.deepEqual(liveGame.view(g).duelParticipants.map(p => p.id), ['a', 'b']);
  assert.equal(liveGame.action(g, { type: 'applause:start' }).ok, false);
  assert.ok(liveGame.action(g, { type: 'draw', excludeDrawn: true }).ok);
  const first = g.live.draw.pid; assert.ok(['a', 'b'].includes(first));
  assert.ok(liveGame.action(g, { type: 'draw', excludeDrawn: true }).ok); assert.notEqual(g.live.draw.pid, first);
  assert.equal(liveGame.action(g, { type: 'draw', excludeDrawn: true }).ok, false);
  liveGame.action(g, { type: 'draw:reset' }); assert.deepEqual(g.live.drawn, []);
  liveGame.action(g, { type: 'duel:end' }); assert.deepEqual(g.live.duel, []);
  for (const p of Object.values(g.players)) p.sid = null;
  assert.equal(liveGame.action(g, { type: 'countdown:start' }).ok, false);
});
test('answer timer pause/resume/expiry and game pause conserve exact time without scoring', () => {
  const g = game(); g.phase = 'answering'; g.ans = 'a';
  assert.equal(liveGame.action(g, { type: 'countdown:cancel' }, 1000).ok, false); assert.equal(g.phase, 'answering'); assert.equal(g.ans, 'a');
  assert.equal(liveGame.action(g, { type: 'timer:start', seconds: -10 }, 1000).ok, false);
  liveGame.action(g, { type: 'timer:start', seconds: 10 }, 1000);
  liveGame.action(g, { type: 'timer:pause' }, 2500); assert.equal(g.live.timer.remainingMs, 8500);
  liveGame.action(g, { type: 'timer:resume' }, 4000); assert.equal(g.live.timer.endsAt, 12500);
  liveGame.action(g, { type: 'pause' }, 5000); assert.equal(g.live.timer.remainingMs, 7500);
  liveGame.advance(g, 99999); assert.equal(g.live.timer.status, 'running');
  liveGame.action(g, { type: 'resume' }, 100000); assert.equal(g.live.timer.endsAt, 107500);
  liveGame.advance(g, 107500); assert.equal(g.live.timer.status, 'expired'); assert.equal(g.ans, 'a');
  liveGame.action(g, { type: 'timer:reset' }); assert.equal(g.live.timer, null);
});
test('applause pause, expiry, and round reset invalidate stale effects, timers, snapshots', () => {
  const g = game(); const round = g.live.roundId;
  liveGame.action(g, { type: 'applause:start' }, 1000);
  liveGame.action(g, { type: 'pause' }, 2000); assert.equal(g.live.applause.remainingMs, 7000);
  liveGame.action(g, { type: 'resume' }, 10000); liveGame.advance(g, 17000); assert.equal(g.live.applause.closed, true);
  g.players.a.presence = { id: 'old', expiresAt: 20000 }; g.undo = ['old'];
  liveGame.clearRound(g); assert.notEqual(g.live.roundId, round); assert.equal(g.live.applause, null); assert.equal(g.players.a.presence, null); assert.deepEqual(g.undo, []);
});

test('real Socket.IO: host + players, authoritative queue, private effects, modes, auth and reconnect', { timeout: 20000 }, async t => {
  const reserve = net.createServer(); await new Promise(resolve => reserve.listen(0, '127.0.0.1', resolve));
  const port = reserve.address().port; await new Promise(resolve => reserve.close(resolve));
  const server = spawn(process.execPath, ['server.js'], { cwd: require('node:path').join(__dirname, '..'), env: { ...process.env, PORT: String(port), HOST_PASS: 'TEST', AFTERPARTY_ENABLED: 'false' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const clients = []; let output = '';
  t.after(async () => { for (const c of clients) c.disconnect(); server.kill(); await new Promise(resolve => server.exitCode !== null ? resolve() : server.once('exit', resolve)); });
  server.stderr.on('data', b => { output += b; });
  await new Promise((resolve, reject) => { server.stdout.on('data', b => { output += b; if (output.includes('Quiz in ascolto')) resolve(); }); server.once('exit', () => reject(new Error(output))); });
  const url = `http://127.0.0.1:${port}`;
  const connect = async () => { const c = client(url, { forceNew: true, transports: ['websocket'], reconnection: false }); clients.push(c); await new Promise((resolve, reject) => { c.once('connect', resolve); c.once('connect_error', reject); }); return c; };
  const send = (c, event, data = {}) => new Promise((resolve, reject) => c.timeout(2500).emit(event, data, (error, r) => error ? reject(error) : resolve(r)));
  const until = async (condition, label = 'state') => { const stop = Date.now() + 3000; while (!condition()) { if (Date.now() > stop) throw new Error('Timed out: ' + label); await wait(10); } };
  const host = await connect(), a = await connect(), b = await connect(), c = await connect(), tv = await connect();
  const room = await send(host, 'host:create', { pass: 'TEST', origin: url }); assert.ok(room.key);
  let state; host.on('state', s => { state = s; });
  const pa = await send(a, 'join', { code: room.code, nick: 'Alpha' }), pb = await send(b, 'join', { code: room.code, nick: 'Beta' }), pc = await send(c, 'join', { code: room.code, nick: 'Gamma' });
  assert.ok(pa.token && pb.token && pc.token);
  const tvInfo = await send(tv, 'tv:join', { code: room.code }); assert.equal(tvInfo.key, undefined);
  assert.equal((await send(a, 'live:act', { type: 'pause' })).ok, false);
  assert.equal((await send(tv, 'host:effect', { pid: pa.pid, kind: 'reaction', value: '👏' })).ok, false);
  assert.ok((await send(tv, 'join', { code: room.code, pid: pa.pid, token: 'wrong' })).err);
  const live = (type, extra = {}) => send(host, 'live:act', { type, requestId: liveGame.id(), ...extra });
  const act = async type => { host.emit('act', { type }); await wait(70); };
  await act('start'); await until(() => state?.started);
  const effectsA = [], effectsB = [], effectsTV = [], hostBuzz = [], hostSfx = [];
  a.on('effect', e => effectsA.push(e)); b.on('effect', e => effectsB.push(e)); tv.on('effect', e => effectsTV.push(e));
  host.on('buzz', e => hostBuzz.push(e)); host.on('sfx', e => hostSfx.push(e));
  let playerBuzz = 0; a.on('buzz', () => playerBuzz++);
  const effectRequest = { pid: pa.pid, kind: 'reaction', value: '👏', requestId: 'same-effect' };
  const effect = await send(host, 'host:effect', effectRequest); assert.ok(effect.ok);
  assert.deepEqual(await send(host, 'host:effect', effectRequest), effect);
  await wait(70); assert.equal(effectsA.length, 1); assert.equal(effectsB.length, 0); assert.equal(effectsTV.length, 0);
  assert.equal((await send(host, 'host:effect', { pid: pa.pid, kind: 'reaction', value: '🔥' })).ok, false);
  await act('open'); await until(() => state.phase === 'open');
  const roundId = state.live.roundId;
  const arrivals = await Promise.all([send(a, 'buzz', { roundId, requestId: 'buzz-a' }), send(b, 'buzz', { roundId, requestId: 'buzz-b' })]);
  assert.deepEqual(arrivals.map(x => x.position).sort(), [1, 2]); await until(() => state.order.length === 2);
  assert.deepEqual(state.order.map(x => x.id), arrivals[0].position === 1 ? [pa.pid, pb.pid] : [pb.pid, pa.pid]);
  assert.equal(hostBuzz.length, 1); assert.equal(playerBuzz, 0); assert.ok(hostBuzz[0].id);
  assert.deepEqual(await send(a, 'buzz', { roundId, requestId: 'buzz-a' }), arrivals[0]);
  assert.equal((await send(a, 'buzz', { roundId })).ok, false);
  assert.ok((await live('timer:start', { seconds: 10 })).ok);
  assert.ok((await live('timer:pause')).ok); await until(() => state.live.timer?.status === 'paused');
  assert.ok((await live('timer:resume')).ok); assert.ok((await live('pause')).ok);
  assert.equal((await send(c, 'buzz', { roundId })).ok, false); assert.ok((await live('resume')).ok);
  await act('wrong'); assert.equal(hostBuzz.length, 2); assert.equal(state.live.timer, null);
  const secondId = state.ans;
  await act('correct'); assert.equal(state.players.find(p => p.id === secondId).score, 1); assert.equal(hostSfx.length, 2);
  await act('undo'); assert.equal(state.players.find(p => p.id === secondId).score, 0); assert.equal(state.ans, secondId);
  await act('newround'); assert.notEqual(state.live.roundId, roundId);
  assert.equal((await send(c, 'buzz', { roundId })).ok, false);
  assert.ok((await live('duel:start', { ids: [pa.pid, pb.pid] })).ok);
  assert.ok((await live('countdown:start')).ok); await until(() => !!state.live.countdown);
  assert.equal((await send(a, 'buzz', { roundId: state.live.roundId })).ok, false);
  assert.ok((await live('pause')).ok); await until(() => state.live.paused);
  const frozen = state.live.countdown.remainingMs; await wait(80);
  assert.ok((await live('resume')).ok); await until(() => !state.live.paused);
  assert.ok(Math.abs(state.live.countdown.remainingMs - frozen) < 100);
  await until(() => state.phase === 'open', 'countdown expiry');
  assert.equal((await send(c, 'buzz', { roundId: state.live.roundId })).ok, false);
  assert.ok((await send(a, 'buzz', { roundId: state.live.roundId })).ok);
  await act('newround'); assert.ok((await live('duel:end')).ok);
  assert.ok((await live('draw', { excludeDrawn: true })).ok); await until(() => !!state.live.draw);
  const drawId = state.live.draw.id; assert.ok([pa.pid, pb.pid, pc.pid].includes(state.live.draw.pid));
  assert.ok((await live('draw:clear')).ok); assert.ok((await live('draw:reset')).ok);
  assert.ok((await live('applause:start')).ok); await until(() => !!state.live.applause);
  const applauseId = state.live.applause.id;
  assert.ok((await send(a, 'applause:react', { id: applauseId, value: '🎉' })).ok);
  assert.equal((await send(a, 'applause:react', { id: applauseId, value: '🎉' })).ok, false);
  assert.equal((await send(b, 'applause:react', { id: 'stale', value: '🎉' })).ok, false);
  assert.ok((await live('applause:stop')).ok); await until(() => state.live.applause.closed); assert.equal(state.live.applause.counts['🎉'], 1);
  assert.ok((await live('applause:clear')).ok); assert.ok((await live('spotlight', { pid: pa.pid })).ok);
  await wait(710);
  const presence = await send(host, 'host:effect', { pid: pa.pid, kind: 'presence' }); assert.ok(presence.ok);
  let confirmation; host.on('presence:confirmed', x => { confirmation = x; });
  assert.equal((await send(b, 'presence:reply', { id: presence.id })).ok, false);
  a.disconnect(); const resumed = await connect(); let recoveredMe; let replayed = 0;
  resumed.on('me', x => { recoveredMe = x; }); resumed.on('effect', () => replayed++);
  assert.ok((await send(resumed, 'join', { ...pa, nick: 'Alpha' })).token);
  await until(() => !!recoveredMe?.presence); assert.equal(recoveredMe.presence.id, presence.id); assert.equal(replayed, 0);
  assert.equal(recoveredMe.live.draw?.id, undefined); assert.notEqual(drawId, undefined);
  assert.ok((await send(resumed, 'presence:reply', { id: presence.id })).ok); await until(() => !!confirmation); assert.equal(confirmation.pid, pa.pid);
  assert.equal((await send(resumed, 'presence:reply', { id: presence.id })).ok, false);
  assert.equal(state.players.reduce((sum, p) => sum + p.score, 0), 0);
  assert.equal((await send(host, 'host:effect', { pid: pb.pid, kind: 'message', value: '<script>alert(1)</script>' })).ok, false);
  b.disconnect(); await until(() => !state.players.find(p => p.id === pb.pid).on);
  assert.equal((await send(host, 'host:effect', { pid: pb.pid, kind: 'reaction', value: '👏' })).ok, false);
});
