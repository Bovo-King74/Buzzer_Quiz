'use strict';
// Uses Socket.IO's bundled client: no extra production or test dependencies.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const { Server } = require('socket.io');
const client = require('../node_modules/socket.io/client-dist/socket.io.js');
const mount = require('../plugins/afterparty');
test('real WebSockets: isolated namespaces, auth, complete round, reconnect, and hostile input', { timeout: 15000 }, async t => {
  const server=http.createServer(), io=new Server(server), plugin=mount(io,{password:'TEST'}), clients=[];
  t.after(async()=>{for(const c of clients)c.disconnect();plugin.close();await io.close();});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const url=`http://127.0.0.1:${server.address().port}`;
  const connect=async namespace=>{const c=client(url+namespace,{transports:['websocket'],forceNew:true,reconnection:false});clients.push(c);await new Promise((resolve,reject)=>{c.once('connect',resolve);c.once('connect_error',reject)});return c;};
  const send=(c,event,data={})=>new Promise((resolve,reject)=>c.timeout(2000).emit(event,data,(err,r)=>err?reject(err):resolve(r)));
  const host=await connect('/afterparty'), a=await connect('/afterparty'), b=await connect('/afterparty'), main=await connect('/');
  let mainEvents=0;main.on('state',()=>mainEvents++);
  assert.equal((await send(host,'create',{password:'wrong'})).ok,false);
  const room=await send(host,'create',{password:'TEST'});assert.ok(room.ok);
  const pa=await send(a,'join',{code:room.code,name:'Alpha'}),pb=await send(b,'join',{code:room.code,name:'Beta'});
  assert.ok(pa.ok&&pb.ok);
  const guest=await connect('/afterparty');
  const transient=await send(guest,'join',{code:room.code,name:'Temporanei'});
  assert.equal(plugin.game.room(room.code).players.length,3);
  assert.ok((await send(guest,'leave')).ok);
  assert.equal(plugin.game.room(room.code).players.length,2);
  const returning=await send(guest,'join',{code:room.code,name:'Temporanei'});
  const removable=plugin.game.identity(plugin.game.room(room.code),returning.token);
  assert.equal((await send(a,'remove',{player:removable.id})).ok,false);
  assert.ok((await send(host,'remove',{player:removable.id})).ok);
  assert.equal(plugin.game.room(room.code).players.length,2);
  assert.equal((await send(guest,'resume',returning)).ok,false);
  assert.equal((await send(a,'advance')).ok,false);
  assert.ok((await send(host,'advance',{round:0,phase:'lobby'})).ok);
  assert.ok((await send(a,'submit',{text:'Una risposta molto falsa',round:1})).ok);
  assert.ok((await send(b,'submit',{text:'Una seconda risposta falsa',round:1})).ok);
  const internal=plugin.game.room(room.code), truth=internal.options.find(o=>o.truth);
  assert.equal(internal.phase,'vote');
  assert.ok((await send(a,'vote',{option:truth.id,round:1})).ok);
  assert.ok((await send(b,'vote',{option:truth.id,round:1})).ok);
  assert.equal(internal.phase,'reveal');assert.deepEqual(internal.players.map(p=>p.score),[1000,1000]);
  a.disconnect();const resumed=await connect('/afterparty');assert.ok((await send(resumed,'resume',pa)).ok);
  assert.equal((await send(resumed,'resume',{code:room.code,token:'é'.repeat(36)})).ok,false);
  assert.equal(mainEvents,0);
  assert.equal((await send(host,'advance',{round:0,phase:'lobby'})).ok,false);
  assert.ok((await send(host,'advance',{round:1,phase:'reveal'})).ok);assert.equal(internal.round,2);
});
